//! Part catalog (docs/plan/07 section 3).
//!
//! The built-in catalog of the assembler ([`builtin`]): standard bricks, plates,
//! tiles and a baseplate built by the part evaluator, each with a render mesh,
//! integer-LDU boxes and connectors derived from its features ([`shape`]); and
//! the LDraw pack ([`pack`], written by [`ldraw`]): a curated subset of the
//! user's own copy of the LDraw Parts Library, turned into meshes, boxes and
//! connectors derived from the primitives each part references.
//!
//! The LDraw Parts Library is fetched by the user at runtime and never vendored
//! (CC BY attribution travels with every pack; see LICENSE-POLICY.md and
//! docs/plan/12). Still to do (docs/plan/11, M3a): clip, hinge and ball joints,
//! occupancy masks, LOD hulls.

