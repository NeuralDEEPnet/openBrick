/// The LDraw library attribution line every client must show.
pub const LDRAW_ATTRIBUTION: &str =
    "This software uses the LDraw Parts Library (https://www.ldraw.org).";

/// Index of a part in a [`Catalog`].
pub type PartId = u32;

/// Where a catalog part comes from.
#[derive(Clone, Copy, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Origin {
    /// Generated by the part evaluator; ships with the program.
    Builtin,
    /// From an LDraw pack the user imported.
    Ldraw,
}

/// One catalog entry.
#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct CatalogPart {
    pub id: String,
    pub name: String,
    /// The generated body kind of a built-in part; `None` for pack parts.
    pub body: Option<builtin::Body>,
    pub origin: Origin,
    /// Palette category: `Brick`, `Plate`, `Tile` for built-ins, the LDraw category for pack parts.
    pub category: String,
    pub connectivity: Connectivity,
    /// Joint kinds the part has that are not modelled (`clip`, `hinge`, `ball`, `socket`).
    pub joints: Vec<String>,
    /// Footprint in studs along X then Z.
    pub studs: [u32; 2],
    pub height_ldu: i32,
    pub base: bool,
    pub shape: PartShape,
}

/// The pack a catalog carries, as `.obrick` files name it.
#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct PackRef {
    /// `ldraw`.
    pub id: String,
    /// The library version, `2026-10`.
    pub library: String,
    /// The pack's SHA-256 (hex).
    pub fingerprint: String,
}

/// The parts the engine can place, by [`PartId`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Catalog {
    pub parts: Vec<CatalogPart>,
    /// The pack whose parts follow the built-in ones, if one is loaded.
    pub pack: Option<PackRef>,
}

impl Catalog {
    /// The built-in catalog, built once per process with the evaluator at
    /// [`Lod::Low`] (the boxes and connectors do not depend on the level of
    /// detail).
    pub fn builtin() -> Result<&'static Catalog, CatalogError> {
        static CATALOG: OnceLock<Result<Catalog, CatalogError>> = OnceLock::new();
        CATALOG
            .get_or_init(|| {
                let mut parts = Vec::with_capacity(BUILTIN.len());
                for spec in BUILTIN {
                    let built = builtin::build(spec, Lod::Low)?;
                    parts.push(CatalogPart::new(spec, &built));
                }
                Ok(Catalog { parts, pack: None })
            })
            .as_ref()
            .map_err(Clone::clone)
    }

    /// The part with catalog id `id`.
    pub fn find(&self, id: &str) -> Option<PartId> {
        self.parts
            .iter()
            .position(|p| p.id == id)
            .map(|i| i as PartId)
    }

    /// This catalog with the parts of `pack` after its own (so existing part
    /// numbers, and every built-in id, stay as they are).
    pub fn with_pack(&self, pack: &Pack) -> Catalog {
        let mut parts: Vec<CatalogPart> = self
            .parts
            .iter()
            .filter(|p| p.origin == Origin::Builtin)
            .cloned()
            .collect();
        for p in &pack.header.parts {
            parts.push(CatalogPart::from_pack(p));
        }
        Catalog {
            parts,
            pack: Some(PackRef {
                id: pack.header.id.clone(),
                library: pack.header.library.clone(),
                fingerprint: pack.fingerprint().to_string(),
            }),
        }
    }

    pub fn get(&self, part: PartId) -> Option<&CatalogPart> {
        self.parts.get(part as usize)
    }

    pub fn len(&self) -> usize {
        self.parts.len()
    }

    pub fn is_empty(&self) -> bool {
        self.parts.is_empty()
    }
}

impl CatalogPart {
    /// The entry of a built-in part from its build.
    pub fn new(spec: &BuiltinSpec, built: &BuiltPart) -> CatalogPart {
        CatalogPart {
            id: spec.id.to_string(),
            name: spec.name.to_string(),
            body: Some(spec.body),
            origin: Origin::Builtin,
            category: match spec.body {
                builtin::Body::Brick => "Brick",
                builtin::Body::Plate => "Plate",
                builtin::Body::Tile => "Tile",
            }
            .to_string(),
            connectivity: Connectivity::Derived,
            joints: Vec::new(),
            studs: spec.studs,
            height_ldu: built.height_ldu,
            base: spec.base,
            shape: built.shape.clone(),
        }
    }

    /// The entry of a pack part.
    pub fn from_pack(p: &PackPart) -> CatalogPart {
        CatalogPart {
            id: p.id.clone(),
            name: p.name.clone(),
            body: None,
            origin: Origin::Ldraw,
            category: p.category.clone(),
            connectivity: p.connectivity,
            joints: p.joints.clone(),
            studs: p.studs,
            height_ldu: p.height_ldu,
            base: p.category.eq_ignore_ascii_case("baseplate"),
            shape: PartShape {
                body: p.body,
                pick: p.pick,
                connectors: p.connectors.clone(),
            },
        }
    }
}
